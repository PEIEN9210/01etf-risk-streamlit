class DataFetcher:
    """資料抓取（加入品質控制）"""
    
    @staticmethod
    @st.cache_data(ttl=3600)
    def fetch_price_data(etf_list: Dict[str, str], 
                        benchmark: str, 
                        period: str = "2y") -> Dict[str, Optional[pd.DataFrame]]:
        """批次抓取（改為2年資料以提升統計顯著性）"""
        data = {}
        tickers = list(set(list(etf_list.keys()) + [benchmark]))
        
        progress_bar = st.progress(0)
        status_text = st.empty()
        
        for i, code in enumerate(tickers):
            try:
                status_text.text(f"載入 {code}...")
                ticker = yf.Ticker(code)
                df = ticker.history(period=period)
                
                # 資料品質檢查
                if not df.empty and len(df) >= MIN_TRADING_DAYS:
                    # 檢查成交量
                    avg_volume = df['Volume'].mean()
                    if avg_volume >= MIN_AVG_VOLUME:
                        data[code] = df
                        logger.info(f"{code}: {len(df)} 筆資料, 平均量 {avg_volume:.0f}")
                    else:
                        logger.warning(f"{code}: 成交量不足 ({avg_volume:.0f} < {MIN_AVG_VOLUME})")
                        data[code] = None
                else:
                    logger.warning(f"{code}: 資料不足 ({len(df) if not df.empty else 0} < {MIN_TRADING_DAYS})")
                    data[code] = None
                    
            except Exception as e:
                logger.error(f"{code} 失敗: {e}")
                data[code] = None
            
            progress_bar.progress((i + 1) / len(tickers))
        
        progress_bar.empty()
        status_text.empty()
        
        return data
    
    @staticmethod
    @st.cache_data(ttl=900)
    def fetch_latest_price(code: str) -> Optional[float]:
        """最新價格"""
        try:
            ticker = yf.Ticker(code)
            hist = ticker.history(period="5d")
            if not hist.empty:
                return float(hist['Close'].iloc[-1])
        except:
            pass
        return None
    
    @staticmethod
    @st.cache_data(ttl=7200)
    def fetch_dividend_info(etf_code: str) -> DividendInfo:
        """配息資訊（改進：資料品質評級）"""
        stock_code = etf_code.replace('.TW', '').replace('.TWO', '')
        
        # 嘗試 FinMind API
        try:
            url = "https://api.finmindtrade.com/api/v4/data"
            params = {
                "dataset": "TaiwanStockDividend",
                "data_id": stock_code,
                "start_date": (datetime.now() - timedelta(days=400)).strftime('%Y-%m-%d'),
                "token": ""
            }
            
            response = requests.get(url, params=params, timeout=10)
            
            if response.status_code == 200:
                data = response.json()
                if data.get('status') == 200 and data.get('data'):
                    df = pd.DataFrame(data['data'])
                    
                    if not df.empty:
                        df['date'] = pd.to_datetime(df.get('date', df.get('ex_dividend_date')))
                        df = df.sort_values('date', ascending=False)
                        
                        dividend_col = next((col for col in ['cash_dividend', 'CashDividend'] 
                                           if col in df.columns), None)
                        
                        if dividend_col:
                            df[dividend_col] = pd.to_numeric(df[dividend_col], errors='coerce')
                            df = df[df[dividend_col] > 0].dropna(subset=[dividend_col])
                            
                            if not df.empty:
                                one_year_ago = datetime.now() - timedelta(days=365)
                                ttm_df = df[df['date'] >= one_year_ago]
                                ttm_sum = ttm_df[dividend_col].sum()
                                
                                latest_price = DataFetcher.fetch_latest_price(etf_code) or 100
                                ttm_yield = (ttm_sum / latest_price * 100) if latest_price > 0 else 0
                                
                                # 資料品質評級
                                days_ago = (datetime.now() - df.iloc[0]['date']).days
                                if days_ago < 90:
                                    quality = "高"
                                elif days_ago < 180:
                                    quality = "中"
                                else:
                                    quality = "低"
                                
                                return DividendInfo(
                                    latest_date=df.iloc[0]['date'],
                                    latest_amount=float(df.iloc[0][dividend_col]),
                                    ttm_dividend=float(ttm_sum),
                                    ttm_yield=ttm_yield,
                                    data_source="FinMind",
                                    data_quality=quality
                                )
        except Exception as e:
            logger.warning(f"FinMind 失敗: {e}")
        
        # 靜態資料（更新至2025/02/11）
        return DataFetcher._get_static_dividend(stock_code)
    
