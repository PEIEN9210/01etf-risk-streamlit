    @st.cache_data(ttl=3600)
    def fetch_price_data(etf_universe: Dict[str, Dict],
                        benchmark: str,
                        period: str = "3y") -> Dict[str, Optional[pd.DataFrame]]:
        """
        批次抓取（改為3年以支援樣本外測試）
        
        批判：原版2年不足以進行穩健的out-of-sample驗證
        改進：3年資料 = 2年in-sample + 1年out-of-sample
        """
        data = {}
        tickers = list(set(list(etf_universe.keys()) + [benchmark]))
        
        progress_bar = st.progress(0)
        status_text = st.empty()
        
        for i, code in enumerate(tickers):
            try:
                status_text.text(f"載入 {code}...")
                ticker = yf.Ticker(code)
                df = ticker.history(period=period)
                
                if not df.empty and len(df) >= MIN_TRADING_DAYS:
                    avg_volume = df['Volume'].mean()
                    if avg_volume >= MIN_AVG_VOLUME:
                        data[code] = df
                        logger.info(f"{code}: {len(df)} 筆資料, 平均量 {avg_volume:.0f}")
                    else:
                        logger.warning(f"{code}: 成交量不足 ({avg_volume:.0f} < {MIN_AVG_VOLUME})")
                        data[code] = None
                else:
                    logger.warning(f"{code}: 資料不足 ({len(df) if not df.empty else 0} < {MIN_TRADING_DAYS})")
                    data[code] = None
                    
            except Exception as e:
                logger.error(f"{code} 失敗: {e}")
                data[code] = None
            
            progress_bar.progress((i + 1) / len(tickers))
        
        progress_bar.empty()
        status_text.empty()
        
        return data
    
